const textNodes = document.querySelectorAll("[data-i18n]");
const ariaNodes = document.querySelectorAll("[data-i18n-aria-label]");
const altNodes = document.querySelectorAll("[data-i18n-alt]");
const languageButtons = document.querySelectorAll("[data-language]");

function getStoredLanguage() {
  try {
    return window.localStorage.getItem("phanv-language");
  } catch {
    return null;
  }
}

function storeLanguage(language) {
  try {
    window.localStorage.setItem("phanv-language", language);
  } catch {
    // The language still changes when storage is unavailable.
  }
}

function applyLanguage(language) {
  const selected = translations[language] ? language : "pt";
  const copy = translations[selected];

  document.documentElement.lang = copy.htmlLang;
  document.title = "Phoenix Ashnova — PHANV";
  document.querySelector('meta[name="description"]').content = copy.metaDescription;
  document.querySelector('meta[property="og:description"]').content = copy.ogDescription;

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) node.textContent = copy[key];
  });

  ariaNodes.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    if (copy[key]) node.setAttribute("aria-label", copy[key]);
  });

  altNodes.forEach((node) => {
    const key = node.dataset.i18nAlt;
    if (copy[key]) node.setAttribute("alt", copy[key]);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === selected));
  });

  storeLanguage(selected);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.language));
});

const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
const storedLanguage = getStoredLanguage();
const browserLanguage = navigator.language?.toLowerCase().startsWith("pt") ? "pt" : "en";
applyLanguage(requestedLanguage || storedLanguage || browserLanguage);

document.getElementById("year").textContent = String(new Date().getFullYear());
